class SourceIdentityTests(unittest.TestCase):
    """Compare independent file edits without rebuilding the native distribution."""

    def setUp(self):
        """Copy real resource bytes and build inputs into an isolated source tree."""
        temporary = tempfile.TemporaryDirectory(prefix="ish-source-identity-")
        self.addCleanup(temporary.cleanup)
        self.directory = Path(temporary.name)
        self.root = self.directory / "project"
        for relative in (*BUILD_INPUTS, *RESOURCES, *DOCUMENTS):
            target = self.root / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes((ROOT / relative).read_bytes())
        (self.root / "src/ish/__init__.py").write_text('__version__ = "fixture"\n')

    def test_native_and_language_resource_edits_change_identity(self):
        """Native engine behavior and language content are part of source identity."""
        original = source_digest(self.root)
        for relative in RESOURCES:
            with self.subTest(resource=relative):
                path = self.root / relative
                content = path.read_bytes()
                try:
                    path.write_bytes(content + b"\nfixture resource change\n")
                    self.assertNotEqual(source_digest(self.root), original)
                finally:
                    path.write_bytes(content)
                self.assertEqual(source_digest(self.root), original)

    def test_new_resource_names_and_contents_change_identity(self):
        """Adding, renaming or removing a resource cannot preserve the same identity."""
        original = source_digest(self.root)
        path = self.root / "src/ish/terminal/native/extra.c"
        path.write_text("int extra;\n")
        added = source_digest(self.root)
        self.assertNotEqual(added, original)
        renamed = path.with_name("renamed.c")
        path.rename(renamed)
        self.assertNotEqual(source_digest(self.root), added)
        renamed.unlink()
        self.assertEqual(source_digest(self.root), original)

    def test_generated_files_do_not_change_source_identity(self):
        """Caches, compiled outputs and build directories do not impersonate source edits."""
        original = source_digest(self.root)
        for relative in (
            "src/ish/__pycache__/cached.cpython-312.pyc",
            "src/ish/cached.pyc",
            "src/ish/native.so",
            "src/ish/native.o",
            "src/ish.egg-info/PKG-INFO",
            "src/ish.dist-info/RECORD",
            ".cache/build/result.json",
            "build/lib/ish/copied.py",
            "dist/ish.whl",
        ):
            path = self.root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(b"generated bytes")
        self.assertEqual(source_digest(self.root), original)

    def test_build_inputs_and_native_source_change_identity(self):
        """Build policy and native source are included alongside Python and resources."""
        original = source_digest(self.root)
        for relative in (*BUILD_INPUTS, "src/ish/__init__.py"):
            with self.subTest(path=relative):
                path = self.root / relative
                content = path.read_bytes()
                try:
                    path.write_bytes(content + b"\nchanged\n")
                    self.assertNotEqual(source_digest(self.root), original)
                finally:
                    path.write_bytes(content)
        (self.root / "src/ish/native.c").write_text("int main(void) { return 0; }\n")
        self.assertNotEqual(source_digest(self.root), original)

    def test_checkout_location_does_not_change_identity(self):
        """Moving identical source to another absolute directory keeps its identity."""
        relocated = self.directory / "relocated"
        shutil.copytree(self.root, relocated)
        self.assertEqual(source_digest(self.root), source_digest(relocated))

    def test_missing_build_input_is_rejected(self):
        """An incomplete source tree cannot silently produce a smaller manifest."""
        (self.root / "uv.lock").unlink()
        with self.assertRaises(FileNotFoundError):
            source_digest(self.root)

    def test_published_guide_and_bundles_change_identity(self):
        """The artifact identity covers the usage instructions shipped to users."""
        original = source_digest(self.root)
        for relative in DOCUMENTS:
            with self.subTest(path=relative):
                path = self.root / relative
                content = path.read_bytes()
                try:
                    path.write_bytes(content + b"\nchanged\n")
                    self.assertNotEqual(source_digest(self.root), original)
                finally:
                    path.write_bytes(content)

    def test_published_guide_keeps_local_links_and_excludes_caches(self):
        """Relocated users receive editable bundles without development bytecode."""
        cache = self.root / "bundles/plugins/terminal_search/__pycache__"
        cache.mkdir()
        (cache / "__init__.cpython-312.pyc").write_bytes(b"not a source file")
        destination = self.directory / "release"
        copy_documentation(self.root, destination)
        files = sorted(
            path.relative_to(destination).as_posix()
            for path in destination.rglob("*")
            if path.is_file()
        )
        self.assertEqual(files, sorted(DOCUMENTS))
        for relative in DOCUMENTS:
            self.assertEqual(
                (destination / relative).read_bytes(),
                (self.root / relative).read_bytes(),
            )


@unittest.skipUnless(sys.platform.startswith("linux"), "requires POSIX launchers")
class LauncherTests(unittest.TestCase):
    """Execute the public launcher after relocation and observe interpreter argv."""

    def test_relocated_launchers_preserve_arguments_directory_and_status(self):
        """ish selects the native terminal entry point without rewriting native shell arguments."""
        with tempfile.TemporaryDirectory(prefix="ish-launchers-") as temporary:
            directory = Path(temporary)
            original = directory / "original"
            python = original / "bin/python/bin/python3"
            python.parent.mkdir(parents=True)
            python.write_text(
                f"#!{sys.executable}\n"
                "import json, os, sys\n"
                "print(json.dumps({'args': sys.argv[1:], 'cwd': os.getcwd(), "
                "'term': os.environ['TERM']}))\n"
                "sys.exit(7)\n"
            )
            python.chmod(0o755)
            for name in ("ish",):
                launcher = original / "bin" / name
                shutil.copy2(ROOT / f"tools/{name}-launcher.sh", launcher)
                launcher.chmod(0o755)
                (original / name).symlink_to(f"./bin/{name}")
            relocated = directory / "relocated space"
            original.rename(relocated)
            outside = directory / "caller"
            outside.mkdir()
            env = dict(os.environ, TERM="fixture-terminal")
            env["PATH"] = str(relocated) + os.pathsep + env.get("PATH", "")
            for name, module in (("ish", "ish"),):
                with self.subTest(launcher=name):
                    result = subprocess.run(
                        [name, "--shell-arg", "a b", "유니코드"],
                        cwd=outside,
                        env=env,
                        capture_output=True,
                        text=True,
                        timeout=10,
                        check=False,
                    )
                    self.assertEqual(result.returncode, 7, result.stderr)
                    self.assertEqual(result.stderr, "")
                    self.assertEqual(
                        json.loads(result.stdout),
                        {
                            "args": [
                                "-I",
                                "-m",
                                module,
                                "--shell-arg",
                                "a b",
                                "유니코드",
                            ],
                            "cwd": str(outside),
                            "term": "fixture-terminal",
                        },
                    )


class NativeBundleTests(unittest.TestCase):
    """Observe installed native bytes and relocation through the real VT engine."""

    def test_verified_engine_does_not_repeat_the_full_native_build(self):
        """An existing engine needs source licenses and the current private C bridge."""
        from ish.terminal.vt import DEFAULT_LIBRARY

        with tempfile.TemporaryDirectory(prefix="ish-native-reuse-") as temporary:
            root = Path(temporary)
            install = root / ".cache/ghostty-vt/install"
            install.parent.mkdir(parents=True)
            install.symlink_to(DEFAULT_LIBRARY.parent.parent, target_is_directory=True)
            tool = root / "tools/build_ghostty_vt.py"
            tool.parent.mkdir()
            record = root / "build-arguments"
            tool.write_text(
                "import json, sys\nfrom pathlib import Path\n"
                f"with Path({str(record)!r}).open('a') as output:\n"
                "    output.write(json.dumps(sys.argv[1:]) + '\\n')\n"
            )
            cache = root / "source-cache"
            prepare_native(root, cache)
            self.assertEqual(
                [json.loads(line) for line in record.read_text().splitlines()],
                [["--cache-dir", str(cache), "--prepare"], ["--bridge-only"]],
            )

    def test_native_installation_survives_source_path_removal(self):
        """A relocated runtime loads the shipped bridge and keeps Unicode cells."""
        from ish.terminal.vt import DEFAULT_LIBRARY

        with tempfile.TemporaryDirectory(prefix="ish-native-package-") as temporary:
            work = Path(temporary)
            source = work / "native/lib"
            shutil.copytree(DEFAULT_LIBRARY.parent, source, symlinks=True)
            shutil.copy2(
                DEFAULT_LIBRARY.parent.parent / "ish-native.json",
                source.parent / "ish-native.json",
            )
            licenses = work / "engine-license"
            licenses.mkdir()
            (licenses / "LICENSE").write_text("fixture license\n")
            (licenses / "LICENSE-APACHE").write_text("fixture dependency license\n")
            bundle = work / "original/bin"
            manifest = copy_native(source, bundle, (licenses,))
            self.assertEqual(manifest["engine"], "1.0.1")
            self.assertEqual(manifest["source"], "upstream")
            self.assertEqual(
                manifest["provenance_sha256"],
                hashlib.sha256(
                    (source.parent / "ish-native.json").read_bytes()
                ).hexdigest(),
            )
            runtime = bundle / "python"
            runtime.mkdir()
            (runtime / "ish-runtime.json").write_text("{}")
            relocated = work / "relocated directory"
            bundle.parent.rename(relocated)
            shutil.rmtree(source)
            code = """
import sys
from pathlib import Path
sys.prefix = sys.argv[1]
from ish.terminal.vt import DEFAULT_LIBRARY, Terminal
expected = Path(sys.argv[1]).parent / 'libexec/ghostty-vt/libish_vt.so'
assert DEFAULT_LIBRARY == expected, DEFAULT_LIBRARY
with Terminal(24, 4, lambda _: None) as terminal:
    terminal.feed('INSTALLED 한글'.encode())
    assert ''.join(value for _, value in terminal.frame().lines[0]).rstrip() == 'INSTALLED 한글'
print('relocated native engine loaded')
"""
            environment = dict(os.environ, PYTHONPATH=str(ROOT / "src"))
            environment.pop("ISH_GHOSTTY_LIB", None)
            result = subprocess.run(
                [sys.executable, "-c", code, str(relocated / "bin/python")],
                cwd=work,
                env=environment,
                capture_output=True,
                text=True,
                timeout=30,
            )
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(result.stdout, "relocated native engine loaded\n")
            self.assertEqual(
                (relocated / "bin/licenses/engine-license/LICENSE").read_text(),
                "fixture license\n",
            )
            self.assertEqual(
                (relocated / "bin/licenses/engine-license/LICENSE-APACHE").read_text(),
                "fixture dependency license\n",
            )
            self.assertTrue(
                (relocated / "bin/libexec/ghostty-vt/libghostty-vt.so").is_symlink()
            )
            self.assertEqual(
                (
                    relocated / "bin/licenses/ish-native-build/ish-native.json"
                ).read_bytes(),
                (source.parent / "ish-native.json").read_bytes(),
            )

    def test_missing_bundled_bridge_does_not_select_source_cache(self):
        """A marked but damaged installation retains its expected installed path."""
        from ish.runtime.distribution import bundled_vt_library

        with tempfile.TemporaryDirectory(prefix="ish-missing-native-") as temporary:
            runtime = Path(temporary) / "bin/python"
            runtime.mkdir(parents=True)
            (runtime / "ish-runtime.json").write_text("{}")
            with patch("sys.prefix", str(runtime)):
                self.assertEqual(
                    bundled_vt_library(),
                    Path(temporary) / "bin/libexec/ghostty-vt/libish_vt.so",
                )
